-- 12a. conversation_audit (job-scoped owner isolation)
alter table public.conversation_audit enable row level security;
drop policy if exists "Users manage own conversation audit" on public.conversation_audit;
create policy "Users manage own conversation audit"
    on public.conversation_audit
    for all
    using (
        exists (
            select 1 from public.jobs j
            where j.id::text = conversation_audit.job_id
              and j.user_id = auth.uid()
        )
    )
    with check (
        exists (
            select 1 from public.jobs j
            where j.id::text = conversation_audit.job_id
              and j.user_id = auth.uid()
        )
    );

