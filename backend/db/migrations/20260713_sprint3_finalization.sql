-- 11. Extend jobs.status CHECK constraint to cover Sprint 3 interactive states.
--     Additive + backward-safe: existing rows keep their current status; the new
--     enum list is a SUPERSET of the old one, so no existing value is rejected.
-- =============================================================================
do $$
begin
    if exists (
        select 1 from pg_constraint
        where conname = 'jobs_status_check'
          and conrelid = 'public.jobs'::regclass
    ) then
        alter table public.jobs drop constraint jobs_status_check;
    end if;
end $$;

alter table public.jobs
    add constraint jobs_status_check
    check (
        status in (
            'queued',
            'claimed',
            'running',
            'waiting_for_llm',
            'waiting_for_user',
            'approved',
            'rejected',
            'resumed',
            'paused',
            'cancelled',
            'completed',
            'failed',
            'abandoned',
            'recoverable'
        )
    );

