-- 12g. project_specifications (conversation-scoped; owner derived via job linkage)
-- Note: project_specifications stores conversation_id only (no direct user_id).
-- Owner isolation is enforced through the owning job when one exists; where no job
-- linkage is available the policy falls back to the stored user_id column.
alter table public.project_specifications enable row level security;
drop policy if exists "Users manage own project specifications" on public.project_specifications;
create policy "Users manage own project specifications"
    on public.project_specifications
    for all
    using (
        user_id = auth.uid()::text
        or exists (
            select 1 from public.jobs j
            where j.conversation_id = project_specifications.conversation_id
              and j.user_id = auth.uid()
        )
    )
    with check (
        user_id = auth.uid()::text
        or exists (
            select 1 from public.jobs j
            where j.conversation_id = project_specifications.conversation_id
              and j.user_id = auth.uid()
        )
    );

