# Objective 2 — RequirementProjectionEngine + SnapshotProjection
# ---------------------------------------------------------------------------

class RequirementProjectionEngine:
    """Deterministic projection: events → snapshot (Objective 2).

    This is a PURE function (wrapped in a class for namespacing).
    Given a ``RequirementResolutionContext``, it produces a
    ``RequirementSnapshot``.

    Responsibilities (NO planner logic):
      - replay events in order
      - apply resolution policy
      - compute active components
      - compute assumptions
      - compute unknowns
      - compute conflicts
      - produce snapshot hash
    """
    @classmethod
    def project(cls, context: RequirementResolutionContext) -> RequirementSnapshot:
        """Deterministic projection.  Same context → same snapshot."""
        import time
        start_ms = int(time.time() * 1000)

        events = sorted(context.events, key=lambda e: e.timestamp)
        if not events:
            snap = RequirementSnapshot()
            snap.projection_version = 1
            return snap

        # ── Apply policy ─────────────────────────────────────────────────
        active_events = cls._apply_policy(events, context.policy)

        # ── Build snapshot fields ────────────────────────────────────────
        newest = active_events[-1] if active_events else events[-1]
        context.intent = newest.intent
        context.resolved_text = newest.payload.get("requirement_text", "")

        # Merge components (newest wins per component_type under NEWEST_WINS)
        comp_map: dict[str, DynamicComponent] = {}
        for ev in active_events:
            for c_dict in (ev.payload.get("components") or []):
                ct = c_dict.get("component_type", "UNKNOWN")
                comp = DynamicComponent(
                    id=f"{ct}-{len(comp_map) + 1}",
                    component_type=ct,
                    framework=c_dict.get("framework", "UNKNOWN"),
                    language=c_dict.get("language", "UNKNOWN"),
                    notes=c_dict.get("notes", ""),
                )
                comp_map[ct] = comp

        context.active_components = list(comp_map.values())

        # ── Compute unknowns + assumptions ─────────────────────────────
        context.unknowns = cls._compute_unknowns(context.active_components)
        context.assumptions = cls._compute_assumptions(context)

        # ── Detect conflicts ────────────────────────────────────────────
        context.conflicts = cls._detect_conflicts(active_events)

        # ── Assemble snapshot ───────────────────────────────────────────
        snap = RequirementSnapshot(
            snapshot_id=str(uuid.uuid4()),
            source_events=[e.event_id for e in events],
            requirement_text=context.resolved_text,
            intent=context.intent,
            components=context.active_components,
            assumptions=context.assumptions,
            conflicts=context.conflicts,
            event_count=len(events),
            revision_count=len(events),
        )
        snap.hash = cls._snapshot_hash(snap)
        snap.integrity_status = "valid"
        snap.projection_version = 1
        snap.projection_timestamp = datetime.now(timezone.utc)

        end_ms = int(time.time() * 1000)
        context.replay_duration_ms = end_ms - start_ms
        snap.replay_duration = context.replay_duration_ms

        return snap

    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    # Policy application
    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

    @classmethod
    def _apply_policy(
        cls,
        events: list[RequirementEvent],
        policy: ResolutionPolicy,
    ) -> list[RequirementEvent]:
        """Return the list of active (non-superseded) events after policy."""
        # Step 1: remove superseded events (all policies)
        superseded: set[str] = set()
        for ev in events:
            superseded.update(ev.supersedes)
        active = [ev for ev in events if ev.event_id not in superseded]

        if policy == ResolutionPolicy.NEWEST_WINS:
            # Already correct: all active events are kept; newest wins per field
            return active

        if policy == ResolutionPolicy.MERGE:
            # Keep all active events; conflicts are preserved (not resolved)
            return active

        if policy == ResolutionPolicy.REJECT:
            # If ANY conflict exists, reject ALL events after the first
            frameworks: dict[str, set[str]] = {}
            for ev in events:
                for c in (ev.payload.get("components") or []):
                    ct = c.get("component_type", "UNKNOWN")
                    fw = c.get("framework", "UNKNOWN")
                    frameworks.setdefault(ct, set()).add(fw)
            has_conflict = any(len(v) > 1 for v in frameworks.values())
            if has_conflict:
                # Keep only the first event
                return events[:1]
            return active

        # MANUAL + PRIORITY_WINS: keep all; conflicts recorded but not resolved
        return active

    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    # Helpers
    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

    @classmethod
    def _compute_unknowns(cls, components: list[DynamicComponent]) -> dict[str, UnknownType]:
        result: dict[str, UnknownType] = {}
        for c in components:
            if c.framework == "UNKNOWN":
                utype = UnknownType.REQUIRED if c.component_type in ("backend", "database") else UnknownType.OPTIONAL
                result[c.id] = utype
        return result

    @classmethod
    def _compute_assumptions(cls, context: RequirementResolutionContext) -> list[Assumption]:
        assumptions: list[Assumption] = []
        for c in context.active_components:
            if c.framework == "UNKNOWN":
                assumptions.append(Assumption(
                    field=f"{c.component_type}.framework",
                    value="UNKNOWN",
                    reason=f"User did not specify {c.component_type} framework.",
                    confidence=0.0,
                    priority=AssumptionPriority.CRITICAL,
                    can_be_confirmed=True,
                    approval_required=True,
                ))
        return assumptions

    @classmethod
    def _detect_conflicts(cls, events: list[RequirementEvent]) -> list[RequirementConflict]:
        conflicts: list[RequirementConflict] = []
        framework_map: dict[str, list[tuple[str, str]]] = {}
        for ev in events:
            for c in ((ev.payload or {}).get("components") or []):
                ct = c.get("component_type", "UNKNOWN")
                fw = c.get("framework", "UNKNOWN")
                framework_map.setdefault(ct, []).append((ev.event_id, fw))
        for ct, entries in framework_map.items():
            unique = {fw for _, fw in entries if fw != "UNKNOWN"}
            if len(unique) > 1:
                conflicts.append(RequirementConflict(
                    conflict_type="framework",
                    description=f"Multiple frameworks for '{ct}': {', '.join(unique)}",
                    conflicting_events=[eid for eid, _ in entries],
                    conflicting_values=list(unique),
                ))
        return conflicts

    @staticmethod
    def _snapshot_hash(snapshot: RequirementSnapshot) -> str:
        canonical = json.dumps(
            snapshot.model_dump(mode="json", exclude={"hash", "integrity_status"}),
            sort_keys=True,
            separators=(",", ":"),
            default=str,
        )
        return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


