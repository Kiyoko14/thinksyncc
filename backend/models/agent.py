    def is_critical_unknown(self) -> list[str]:
        blocked: list[str] = []
        for field_name, utype in self.unknown_fields.items():
            if utype == UnknownType.REQUIRED:
                blocked.append(field_name)
        return blocked

    def readiness_computed(self) -> str:
        if self.is_critical_unknown():
            return "Blocked"
        if any(
            c.unknown_type == UnknownType.REQUIRED
            for c in self.architecture.components
        ):
            return "Blocked"
        if not self.architecture.components:
            return "Partial"
        return "Ready"

    def to_canonical_json(self) -> str:
        return json.dumps(
            self.model_dump(mode="json"),
            sort_keys=True,
            separators=(",", ":"),
            default=str,
        )
    production_ready: bool = False
    missing_info: list[str] = Field(default_factory=list)
    # confidence is REMOVED (Sprint 2B).
    # Replaced by: readiness (Ready|Blocked|Partial) and frozen (bool).
    readiness: str = "Blocked"
    frozen: bool = False
    needs_user_input: bool = False
