    needs_user_input: bool = False
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    # --- Constructors ---
    @classmethod
    def from_dynamic_architecture(
        cls,
        arch: DynamicArchitecture,
        **kwargs: Any,
    ) -> "ProjectSpecification":
        """Build from ``DynamicArchitecture`` (replaces ``from_architecture``)."""
        backend = arch.get_component("backend")
        database = arch.get_component("database")
        return cls(
            architecture=arch,
            framework=backend.framework if backend else "UNKNOWN",
            language=backend.language if backend else "UNKNOWN",
            database_required=(
                database is not None and database.framework != "UNKNOWN"
            ),
            **kwargs,
        )

