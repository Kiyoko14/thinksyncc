class ResolutionPolicy(str, Enum):
    """Configurable resolution policies (Objective 5).

    Policies control HOW the ``RequirementResolutionEngine`` resolves
    conflicting events into a ``RequirementSnapshot``.

    ``NEWEST_WINS``  — default; newest event wins per field/component.
    ``PRIORITY_WINS`` — highest-priority event wins (future: priority
                         will be set by Approval System).
    ``MANUAL``       — conflicts are NOT resolved; user must decide.
    ``MERGE``        — merge non-conflicting fields; keep conflicts.
    ``REJECT``       — reject any event that creates a conflict.
    """
    NEWEST_WINS  = "newest_wins"
    PRIORITY_WINS = "priority_wins"
    MANUAL       = "manual"
    MERGE        = "merge"
    REJECT       = "reject"


@dataclass
class RequirementResolutionContext:
    """Context bundle passed to the resolution engine (Objective 6).

    The engine reads ONLY this context — it never reaches into global
    state, never imports planner/executor, and never calls external APIs.

    This makes the engine fully deterministic and testable.
    """
    policy: ResolutionPolicy = ResolutionPolicy.NEWEST_WINS
    events: list[RequirementEvent] = field(default_factory=list)
    active_components: list[DynamicComponent] = field(default_factory=list)
    assumptions: list[Assumption] = field(default_factory=list)
    conflicts: list[RequirementConflict] = field(default_factory=list)
    unknowns: dict[str, UnknownType] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)

    # ── computed by engine ───────────────────────────────────────────────
    resolved_text: str = ""
    intent: IntentType = IntentType.CREATE
    replay_duration_ms: int = 0
    projection_version: int = 1


