# Objective 8 — RequirementIntegrity (NEW)
# ---------------------------------------------------------------------------
class RequirementIntegrity:
    """Verify integrity of a ``RequirementSnapshot`` independently."""
    @staticmethod
    def verify(snapshot: RequirementSnapshot) -> tuple[bool, list[str]]:
        issues: list[str] = []
        # 1. Hash consistency
        computed = _snapshot_hash(snapshot)
        if snapshot.hash and computed != snapshot.hash:
            issues.append(f"Snapshot hash mismatch: stored={snapshot.hash[:8]} computed={computed[:8]}")
            snapshot.integrity_status = "tampered"
        else:
            snapshot.integrity_status = "valid"

        # 2. Event count consistency
        if snapshot.event_count < 0:
            issues.append("event_count is negative")

        # 3. Conflicts unresolved
        unresolved = [c for c in snapshot.conflicts if c.resolution == "unresolved"]
        if unresolved:
            issues.append(f"{len(unresolved)} unresolved conflict(s)")

        return (len(issues) == 0, issues)

    @staticmethod
    def compute_hash(snapshot: RequirementSnapshot) -> str:
        return _snapshot_hash(snapshot)


