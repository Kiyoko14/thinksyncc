class RelationshipGraph(BaseModel):
    """Relationship graph for architecture components.

    Each component declares what it ``provides``, ``consumes``,
    ``depends_on``, ``required_by``, ``interfaces``, ``runtime``, ``lifecycle``.

    The Planner consumes this graph in Sprint 3 to order execution steps.
    """
    components: list[DynamicComponent] = Field(default_factory=list)

    def build_from(self, components: list[DynamicComponent]) -> "RelationshipGraph":
        self.components = components
        # Auto-populate depends_on / required_by from component.dependencies
        id_map = {c.id: c for c in self.components}
        for c in self.components:
            c.dependencies = c.dependencies or []
            # If dependencies is empty but component_type implies defaults, fill them
            if not c.dependencies:
                if c.component_type == "queue" and id_map.get("backend-api"):
                    c.dependencies.append("backend-api")
        return self

    def get_execution_order(self) -> list[str]:
        """Topological sort (planner will use this in Sprint 3)."""
        # Simplified: just return component IDs in dependency order
        ordered: list[str] = []
        visited: set[str] = set()

        def _dfs(cid: str):
            if cid in visited:
                return
            visited.add(cid)
            c = next((x for x in self.components if x.id == cid), None)
            if c:
                for dep in (c.dependencies or []):
                    _dfs(dep)
            ordered.append(cid)

        for c in self.components:
            _dfs(c.id)
        return ordered

    def to_dict(self) -> dict[str, Any]:
        return {
            "components": [c.component_type for c in self.components],
            "dependencies": {c.id: c.dependencies for c in self.components},
            "execution_order": self.get_execution_order(),
        }


