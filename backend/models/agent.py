class RequirementDocument(BaseModel):
    """Immutable record of WHAT the user wants.

    This is completely SEPARATE from ``ProjectSpecification``.

    - ``revisions`` — append-only version history (never overwritten)
    - ``latest_revision`` — pointer to the latest revision
    - ``timeline`` — summarises how requirements evolved (Objective 2)

    The Planner MUST NEVER read ``RequirementDocument`` directly.
    It MUST always consume ``FrozenSpecification``.
    """
    conversation_id: str = ""
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    revisions: list[RequirementRevision] = Field(default_factory=list)
    latest_revision: int = 0

    def add_revision(
        self,
        requirement_text: str,
        source: str = "user",
        change_reason: str = "",
        changed_fields: list[str] | None = None,
        extracted_components: list[dict[str, Any]] | None = None,
        assumptions: list[Assumption] | None = None,
    ) -> RequirementRevision:
        """Append a new immutable revision.  Returns the new revision."""
        new_version = self.latest_revision + 1
        rev = RequirementRevision(
            version=new_version,
            timestamp=datetime.now(timezone.utc),
            source=source,
            change_reason=change_reason,
            changed_fields=changed_fields or [],
            requirement_text=requirement_text,
            extracted_components=extracted_components or [],
            assumptions=assumptions or [],
        )
        self.revisions.append(rev)
        self.latest_revision = new_version
        self.updated_at = rev.timestamp
        return rev

    def get_latest(self) -> RequirementRevision | None:
        if not self.revisions:
            return None
        return self.revisions[-1]

    def get_revision(self, version: int) -> RequirementRevision | None:
        for r in self.revisions:
            if r.version == version:
                return r
        return None

    def diff(self, v1: int, v2: int) -> dict[str, Any]:
        """Produce a diff between two requirement versions (Objective 7)."""
        r1 = self.get_revision(v1)
        r2 = self.get_revision(v2)
        if not r1 or not r2:
            return {"error": "version not found"}
        added: list[str] = []
        removed: list[str] = []
        modified: list[dict[str, str]] = []
        unchanged: list[str] = []

        # Compare requirement_text naively (line-by-line)
        t1_lines = set(r1.requirement_text.splitlines())
        t2_lines = set(r2.requirement_text.splitlines())
        for line in t2_lines - t1_lines:
            added.append(line[:120])
        for line in t1_lines - t2_lines:
            removed.append(line[:120])
        for line in t1_lines & t2_lines:
            unchanged.append(line[:120])

        return {
            "added": added,
            "removed": removed,
            "modified": modified,
            "unchanged": unchanged,
        }


