# Objective 2 — RequirementResolutionEngine (NEW)
# ---------------------------------------------------------------------------
class RequirementResolutionEngine:
    """Deterministically build a ``RequirementSnapshot`` from events.

    Responsibilities:
      - detect overrides   (event A supersedes event B)
      - detect conflicts   (FastAPI vs Express in same snapshot)
      - detect duplicates  (identical events)
      - detect removals     (event says "remove cache")
      - detect amendments   (event changes one field)
      - resolve newest authoritative value

    The engine is a PURE function: same events → same snapshot.
    """
    @staticmethod
    def resolve(events: list[RequirementEvent]) -> RequirementSnapshot:
        if not events:
            return RequirementSnapshot()

        sorted_events = sorted(events, key=lambda e: e.timestamp)
        snapshot = RequirementSnapshot(
            source_events=[e.event_id for e in sorted_events],
            event_count=len(sorted_events),
        )

        # ── Pass 1: apply overrides (supersedes) ─────────────────────
        active_events: list[RequirementEvent] = []
        superseded = set()
        for ev in sorted_events:
            superseded.update(ev.supersedes)
        active_events = [ev for ev in sorted_events if ev.event_id not in superseded]

        # ── Pass 2: build resolved text + components ───────────────────
        newest = active_events[-1]
        snapshot.intent = newest.intent
        snapshot.requirement_text = newest.payload.get("requirement_text", "")

        # Merge components from all active events (newest wins per component_type)
        comp_map: dict[str, DynamicComponent] = {}
        for ev in active_events:
            for c in (ev.payload.get("components") or []):
                ct = c.get("component_type", "UNKNOWN")
                comp_map[ct] = DynamicComponent(**c)
        snapshot.components = list(comp_map.values())

        # ── Pass 3: detect conflicts ───────────────────────────────────
        frameworks: dict[str, list[str]] = {}   # component_type → [values]
        for ev in active_events:
            for c in (ev.payload.get("components") or []):
                ct = c.get("component_type", "UNKNOWN")
                fw = c.get("framework", "UNKNOWN")
                frameworks.setdefault(ct, []).append(fw)

        conflicts: list[RequirementConflict] = []
        for ct, fws in frameworks.items():
            unique = set(f for f in fws if f != "UNKNOWN")
            if len(unique) > 1:
                conflicts.append(RequirementConflict(
                    conflict_type="framework",
                    description=f"Multiple frameworks for {ct}: {', '.join(unique)}",
                    conflicting_values=list(unique),
                ))
        snapshot.conflicts = conflicts

        # ── Pass 4: compute integrity hash ────────────────────────────
        snapshot.event_count = len(sorted_events)
        snapshot.revision_count = len(sorted_events)   # 1 revision ≈ 1 event for now
        snapshot.hash = _snapshot_hash(snapshot)
        snapshot.integrity_status = "valid"
        return snapshot


