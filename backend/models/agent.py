class EventSchemaVersion(int, Enum):
    """Schema version for RequirementEvent payload (Objective 2).

    v1  — initial (Sprint 2E/2F)
    v2  — added ``notes`` + ``metadata.priority``
    v3  — added ``affects`` + ``supersedes`` validation

    Events are IMMUTABLE.  Older events are UPCAST via ``EventUpcaster``.
    """
    v1 = 1
    v2 = 2
    v3 = 3


# ---------------------------------------------------------------------------
# Objective 3 — EventUpcaster
# ---------------------------------------------------------------------------

class EventUpcaster:
    """Upcast older event schemas to the current internal model (Objective 3).

    Events are immutable — their stored JSON never changes.
    When the schema evolves, ``upcast()`` converts old payloads
    into the CURRENT in-memory representation before projection.

    Dispatch architecture:
      - ``_upcast_v1_to_v1()``   — identity (baseline)
      - ``_upcast_v2_to_v1()``   — (future) v2 → v1
      - ``_upcast_v3_to_v1()``   — (future) v3 → v1
      - Add new methods when schema evolves; never modify old ones.

    This means OLD events continue to work forever.
    """
    CURRENT_VERSION = EventSchemaVersion.v1

    @classmethod
    def upcast(cls, events: list[RequirementEvent]) -> list[RequirementEvent]:
        """Upcast all events to CURRENT_VERSION.

        Returns a NEW list — original events are NOT mutated.

        Fail-fast rules:
          - version == CURRENT_VERSION → return unchanged (identity)
          - version < CURRENT_VERSION  → look up upcaster method;
            if NOT found: raise RuntimeError (unsupported old schema)
          - version > CURRENT_VERSION  → raise RuntimeError
            (future schema version — code must be upgraded first)
          - NO code path silently returns the event unchanged
        """
        result: list[RequirementEvent] = []
        for ev in events:
            target = cls.CURRENT_VERSION
            source = ev.event_schema_version

            if source == target:
                # v1 → v1: identity; event is already current
                result.append(ev)

            elif source > target:
                # Future schema version — code is outdated
                raise RuntimeError(
                    f"[EventUpcaster] event {ev.event_id}: "
                    f"event_schema_version={source.name} is newer than "
                    f"current={target.name}. "
                    f"Upgrade ThinkSync to handle this schema version."
                )

            else:
                # source < target: look up the upcaster method
                method_name = f"_upcast_{source.name}_to_{target.name}"
                upcast_method = getattr(cls, method_name, None)
                if upcast_method is not None:
                    result.append(upcast_method(ev))
                else:
                    raise RuntimeError(
                        f"[EventUpcaster] event {ev.event_id}: "
                        f"no upcaster found for {source.name} → {target.name}. "
                        f"Implement `{method_name}` on EventUpcaster."
                    )
        return result

    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    # Upcast methods (add new ones when schema evolves)
    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

    @classmethod
    def _upcast_v1_to_v1(cls, event: RequirementEvent) -> RequirementEvent:
        """v1 → v1: identity.  Event is already current."""
        return event


