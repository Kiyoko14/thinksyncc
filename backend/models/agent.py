class FrozenSpecification(BaseModel):
    """Immutable, tamper-aware wrapper around a frozen specification."""
    spec: dict[str, Any] = Field(default_factory=dict)
    frozen_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    frozen_hash: str = ""
    version: int = 1
    requirement_version: int | None = None
    is_tampered: bool = False

    def compute_hash(self) -> str:
        import hashlib
        canonical = json.dumps(
            self.spec,
            sort_keys=True,
            separators=(",", ":"),
            default=str,
        )
        return hashlib.sha256(canonical.encode("utf-8")).hexdigest()

    def validate_hash(self) -> bool:
        if not self.frozen_hash:
            return False
        return self.compute_hash() == self.frozen_hash

    def mark_tampered(self) -> None:
        self.is_tampered = True


