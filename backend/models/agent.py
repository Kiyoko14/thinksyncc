class RequirementEventStore:
    """The ONLY authoritative source of truth (Objective 1).

    All requirement events are appended here.
    No other layer may mutate events.
    Snapshots are derived (projected) from this store.

    Responsibilities:
      - append(event)           — immutable append; never edit
      - get_events(conversation_id)  — full event log
      - get_events_since(conversation_id, after_timestamp)
      - rebuild_snapshot(conversation_id, policy)  — deterministic replay
      - compact(conversation_id)  — (future) archive old events

    The store is backed by ``project_specifications.requirement_events``
    (JSONB in Postgres) for now.  A dedicated ``requirement_events``
    table can be introduced in Sprint 3 without changing this interface.
    """
    TABLE = "project_specifications"

    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    # Append (immutable)
    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

    @classmethod
    async def append(cls, conversation_id: str, event: RequirementEvent) -> None:
        """Append ONE immutable event to the store."""
        from core.database import get_supabase
        now = datetime.now(timezone.utc).isoformat()
        try:
            result = (
                get_supabase()
                .table(cls.TABLE)
                .select("requirement_events")
                .eq("conversation_id", conversation_id)
                .maybe_single()
                .execute()
            )
            events: list[dict] = []
            if result and result.data:
                events = result.data.get("requirement_events") or []
            events.append(event.model_dump(mode="json"))
            get_supabase().table(cls.TABLE).upsert({
                "conversation_id": conversation_id,
                "requirement_events": events,
                "updated_at": now,
            }, on_conflict="conversation_id").execute()
        except Exception as exc:
            logger.error("[event_store] append failed: %s", exc, exc_info=True)
            raise

    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    # Read
    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

    @classmethod
    async def get_events(cls, conversation_id: str) -> list[RequirementEvent]:
        """Return the full event log (oldest → newest)."""
        try:
            from core.database import get_supabase
            result = (
                get_supabase()
                .table(cls.TABLE)
                .select("requirement_events")
                .eq("conversation_id", conversation_id)
                .maybe_single()
                .execute()
            )
            if result and result.data:
                raw = result.data.get("requirement_events") or []
                return [RequirementEvent(**r) for r in raw]
        except Exception as exc:
            logger.warning("[event_store] get_events failed: %s", exc)
        return []

    @classmethod
    async def get_events_since(
        cls, conversation_id: str, after: datetime,
    ) -> list[RequirementEvent]:
        """Return events after a given timestamp (for incremental projection)."""
        all_events = await cls.get_events(conversation_id)
        return [e for e in all_events if e.timestamp > after]

    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
    # Deterministic replay (Objective 1 — snapshot = projection)
    # - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

    @classmethod
    async def rebuild_snapshot(
        cls,
        conversation_id: str,
        policy: ResolutionPolicy | None = None,
    ) -> RequirementSnapshot:
        """Rebuild a ``RequirementSnapshot`` from ALL events in the store.

        This is the authoritative rebuild path.  Same events + same policy
        ALWAYS produce the same snapshot (deterministic).

        The result is also persisted as ``latest_snapshot``.
        """
        policy = policy or ResolutionPolicy.NEWEST_WINS
        events = await cls.get_events(conversation_id)
        context = RequirementResolutionContext(policy=policy, events=events)

        snapshot = RequirementProjectionEngine.project(context)
        snapshot.projection_id = str(uuid.uuid4())
        snapshot.projection_timestamp = datetime.now(timezone.utc)

        # Persist
        await cls._save_snapshot(conversation_id, snapshot)
        return snapshot

    @classmethod
    async def _save_snapshot(cls, conversation_id: str, snapshot: RequirementSnapshot) -> None:
        from core.database import get_supabase
        now = datetime.now(timezone.utc).isoformat()
        try:
            get_supabase().table(cls.TABLE).upsert({
                "conversation_id": conversation_id,
                "latest_snapshot": snapshot.model_dump(mode="json"),
                "updated_at": now,
            }, on_conflict="conversation_id").execute()
        except Exception as exc:
            logger.error("[event_store] _save_snapshot failed: %s", exc, exc_info=True)


