class RequirementMapper:
    """Deterministic translation layer.

    RequirementDocument
        ↓
    RequirementMapper.translate()
        ↓
    Architecture + Assumptions

    This layer contains NO planner logic, NO execution logic,
    and NO validation logic.  It ONLY translates.
    """
    @staticmethod
    def translate(
        revision: RequirementRevision,
    ) -> tuple[Any, list[Assumption]]:
        """Translate a ``RequirementRevision`` into ``Architecture`` + ``Assumption`` list.

        This is a pure function — same input ALWAYS produces same output.
        """
        # If the revision already has extracted_components (from LLM), use them
        if revision.extracted_components:
            return _build_architecture_from_components(revision.extracted_components)

        # Otherwise, re-extract from requirement_text
        from services.requirement_discovery import (
            RequirementExtractor, _build_architecture, _build_assumptions,
        )
        arch, assumptions = RequirementExtractor._regex_fallback_architecture(
            revision.requirement_text
        )
        return arch, assumptions


