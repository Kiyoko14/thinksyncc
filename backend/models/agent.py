# Objective 6 — RequirementState (state machine)
# ---------------------------------------------------------------------------
class RequirementState(str, Enum):
    """Lifecycle state machine for a requirement snapshot."""
    DRAFT      = "draft"       # being constructed
    INCOMPLETE = "incomplete"  # missing critical fields
    READY      = "ready"       # complete, can plan
    FROZEN     = "frozen"      # frozen, hash computed
    ARCHIVED   = "archived"    # superseded by newer snapshot


# Legal transitions:
#   DRAFT      → INCOMPLETE | READY
#   INCOMPLETE → READY
#   READY      → FROZEN
#   FROZEN     → ARCHIVED (only when newer snapshot frozen)
#   ARCHIVED   → (terminal)
_ALLOWED_TRANSITIONS: dict[RequirementState, set[RequirementState]] = {
    RequirementState.DRAFT:      {RequirementState.INCOMPLETE, RequirementState.READY},
    RequirementState.INCOMPLETE: {RequirementState.READY},
    RequirementState.READY:      {RequirementState.FROZEN},
    RequirementState.FROZEN:     {RequirementState.ARCHIVED},
    RequirementState.ARCHIVED:   set(),   # terminal
}


def _validate_transition(current: RequirementState, target: RequirementState) -> bool:
    return target in _ALLOWED_TRANSITIONS.get(current, set())


