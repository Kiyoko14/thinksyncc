class DomainEventPublisher:
    """Publish/subscribe for internal domain events (Objective 4).

    This is an in-memory pub/sub.  No Event Bus.  No external dispatch.

    The DEFAULT implementation is **NoOp** (nothing subscribed).
    Future systems subscribe by calling ``subscribe()``.

    Usage (Sprint 3+):
    ```python
    async def on_conflict(event_type, payload):
        # show conflict to user via Approval System
        ...

    DomainEventPublisher.subscribe(
        InternalDomainEvent.CONFLICT_DETECTED, on_conflict
    )
    ```
    """
    _subscribers: dict[InternalDomainEvent, list[Callable[..., Any]]] = {}
    _noop: bool = True        # no subscribers yet → skip publish overhead

    @classmethod
    def subscribe(cls, event_type: InternalDomainEvent, handler: Callable[..., Any]) -> None:
        cls._subscribers.setdefault(event_type, []).append(handler)
        cls._noop = False

    @classmethod
    def unregister(cls, event_type: InternalDomainEvent, handler: Callable[..., Any]) -> None:
        if event_type in cls._subscribers:
            try:
                cls._subscribers[event_type].remove(handler)
            except ValueError:
                pass
            if not cls._subscribers[event_type]:
                del cls._subscribers[event_type]
        cls._noop = len(cls._subscribers) == 0

    @classmethod
    async def publish(cls, event_type: InternalDomainEvent, payload: dict[str, Any]) -> None:
        """Publish an internal domain event to all subscribers."""
        if cls._noop:
            return
        handlers = cls._subscribers.get(event_type, [])
        for h in handlers:
            try:
                result = h(event_type, payload)
                if asyncio.iscoroutine(result):
                    await result
            except Exception as exc:
                logger.warning("[domain_events] handler %s failed: %s", h.__name__, exc)

    @classmethod
    def clear_all(cls) -> None:
        """Remove all subscribers (useful in tests)."""
        cls._subscribers.clear()
        cls._noop = True


