class SnapshotCheckpoint(BaseModel):
    """Checkpoint for incremental replay (Objective 5).

    Instead of replaying ALL events every time, the engine:
      1. Loads the latest checkpoint (full snapshot at event_index)
      2. Replays ONLY events AFTER event_index
      3. Saves a new checkpoint periodically

    This makes replay O(delta) instead of O(total_events).
    """
    checkpoint_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    snapshot_version: int = 1
    event_index: int = 0        # how many events were replayed to produce this
    snapshot_hash: str = ""   # hash of the snapshot at this checkpoint
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    event_count: int = 0    # total events in store at checkpoint time


